start_stack() {
  log "Starting the stack"
  # Existing containers whose config file changed are restarted after `up`, unless `up` replaced them anyway.
  local service before=() restart=() recreate=()
  for service in "${CHANGED_SERVICES[@]}"; do
    before+=("$service=$(compose ps --all --quiet "$service" 2>/dev/null || true)")
  done
  compose up --detach --remove-orphans --wait --wait-timeout 180 2>&1 | sed 's/^/    /' ||
    die "the stack did not come up; see: $COMPOSE_WRAPPER ps and $COMPOSE_WRAPPER logs"
  local entry previous
  for entry in "${before[@]}"; do
    service=${entry%%=*}
    previous=${entry#*=}
    if [[ -n "$previous" && "$previous" == "$(compose ps --all --quiet "$service")" ]]; then
      restart+=("$service")
    fi
  done
  # Compose keeps a container whose image tag now points at a new build, so the services built from this
  # repository are compared with their tag and recreated when they differ.
  local container
  for service in control egress supervisor; do
    container=$(compose ps --all --quiet "$service")
    if [[ "$(docker inspect --format '{{.Image}}' "$container")" != "$(docker image inspect --format '{{.Id}}' "quokkabot/$service:local")" ]]; then
      recreate+=("$service")
    fi
  done
  if [[ ${#recreate[@]} -gt 0 ]]; then
    note "recreating ${recreate[*]} on the new image"
    compose up --detach --no-deps --force-recreate --wait --wait-timeout 180 "${recreate[@]}" 2>&1 | sed 's/^/    /'
  fi
  for service in "${restart[@]}"; do
    [[ " ${recreate[*]} " != *" $service "* ]] || continue
    note "restarting $service for its changed configuration"
    compose restart "$service" >/dev/null
  done
  compose ps --format '{{.Service}}\t{{.State}}\t{{.Status}}' | sed 's/^/    /'
}

# Off-server backups run only when the owner has written $ETC/backup.env (docs/install.md, "Off-server backups").
install_backups() {
  install -m 0755 "$SCRIPT_DIR/backup.sh" /usr/local/sbin/quokkabot-backup
  install -m 0644 "$SCRIPT_DIR/quokkabot-backup.service" /etc/systemd/system/quokkabot-backup.service
  install -m 0644 "$SCRIPT_DIR/quokkabot-backup.timer" /etc/systemd/system/quokkabot-backup.timer
  systemctl daemon-reload
  if [[ ! -f "$ETC/backup.env" ]]; then
    systemctl disable --now --quiet quokkabot-backup.timer 2>/dev/null || true
    log "Off-server backups are off"
    note "Turn them on: docs/install.md, \"Off-server backups\""
    return
  fi
  chmod 0400 "$ETC/backup.env"
  log "Off-server backups"
  systemctl enable --now --quiet quokkabot-backup.timer
  note "daily at 03:15 UTC; next: $(systemctl show quokkabot-backup.timer --property=NextElapseUSecRealtime --value)"
  note "last: $(cat "$DATA/backup/status.json" 2>/dev/null || echo 'none yet; run quokkabot-backup run')"
}

print_setup_link() {
