build_images() {
  log "Building images from $SRC"
  # SOURCE_DATE_EPOCH fixes the image creation time and --provenance=false drops the attestation (it records the
  # build time), so a rebuild from cache keeps the same image id and digest.
  docker build --quiet --provenance=false --sbom=false --build-arg SOURCE_DATE_EPOCH=0 -f "$SRC/images/cli/Dockerfile" -t quokkabot/cli:local "$SRC" >/dev/null
  note "quokkabot/cli"
  docker build --quiet --provenance=false --sbom=false --build-arg SOURCE_DATE_EPOCH=0 -f "$SRC/images/tools/Dockerfile" -t quokkabot/tools:local "$SRC" >/dev/null
  note "quokkabot/tools"
  docker build --quiet --provenance=false --sbom=false --build-arg SOURCE_DATE_EPOCH=0 -f "$SRC/images/browser/Dockerfile" \
    -t quokkabot/browser:local "$SRC" >/dev/null
  note "quokkabot/browser"
  compose build --quiet
  note "quokkabot/control, quokkabot/egress, quokkabot/supervisor"
  IMAGE_CLI=$(image_digest quokkabot/cli:local)
  IMAGE_TOOLS=$(image_digest quokkabot/tools:local)
  IMAGE_BROWSER=$(image_digest quokkabot/browser:local)
}

image_digest() {
  local reference
  reference=$(docker image inspect --format '{{index .RepoDigests 0}}' "$1" 2>/dev/null || true)
  [[ "$reference" =~ ^[^[:space:]]+@sha256:[0-9a-f]{64}$ ]] || die "$1 has no digest; Docker must use the containerd image store"
  printf '%s\n' "$reference"
}

# Every address of this host the egress proxy must refuse: its global addresses (public IPv4/IPv6, docker0,
# Quokka Bot bridges) and the gateway of every Docker bridge network.
host_addresses() {
  {
    ip -o addr show scope global | awk '{print $4}' | cut -d/ -f1
    local network
    for network in $(docker network ls --quiet --filter driver=bridge); do
      docker network inspect --format '{{range .IPAM.Config}}{{println .Gateway}}{{end}}' "$network"
    done
    known_gateways
  } | grep -E '^[0-9a-fA-F:.]+$' | sort -u | paste -sd, -
}

