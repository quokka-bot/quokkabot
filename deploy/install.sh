# Reads KEY=VALUE lines from quokkabot.env without executing anything.
env_value() {
  local key=$1
  [[ -f "$ENV_FILE" ]] || return 0
  sed -n "s/^$key=//p" "$ENV_FILE" | tail -1
}

readonly UUID_PATTERN='^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'

# The agent slots: QUOKKABOT_AGENTS and one id per slot (QUOKKABOT_AGENT_<N>_ID), generated once and kept in
# quokkabot.env. Ids of slots above QUOKKABOT_AGENTS stay in the file, so lowering and raising the number again brings
# the same agents (and their data) back. Read before the firewall, which needs the slot count.
load_agent_slots() {
  QUOKKABOT_AGENTS=${QUOKKABOT_AGENTS:-$(env_value QUOKKABOT_AGENTS)}
  QUOKKABOT_AGENTS=${QUOKKABOT_AGENTS:-$DEFAULT_AGENTS}
  [[ "$QUOKKABOT_AGENTS" =~ ^[1-9][0-9]*$ && "$QUOKKABOT_AGENTS" -le $MAX_AGENTS ]] ||
    die "QUOKKABOT_AGENTS must be a number from 1 to $MAX_AGENTS (found '$QUOKKABOT_AGENTS')"
  AGENT_IDS=()
  KEPT_AGENT_IDS=()
  local index id
  for ((index = 1; index <= MAX_AGENTS; index++)); do
    id=$(env_value "QUOKKABOT_AGENT_${index}_ID")
    if [[ $index -gt $QUOKKABOT_AGENTS ]]; then
      [[ -z "$id" ]] || KEPT_AGENT_IDS+=("$index=$id")
      continue
    fi
    if [[ -z "$id" ]]; then
      id=$(python3 -c 'import uuid; print(uuid.uuid4())')
      note "new agent slot $index id $id"
    fi
    [[ "$id" =~ $UUID_PATTERN ]] || die "bad QUOKKABOT_AGENT_${index}_ID: $id"
    AGENT_IDS+=("$id")
  done
  if [[ ${#KEPT_AGENT_IDS[@]} -gt 0 ]]; then
    note "slots above $QUOKKABOT_AGENTS are not provisioned; their agents and data stay on disk: ${KEPT_AGENT_IDS[*]%%=*}"
  fi
}

load_settings() {
  log "Settings"
  QUOKKABOT_DOMAIN=${QUOKKABOT_DOMAIN:-$(env_value QUOKKABOT_DOMAIN)}
  QUOKKABOT_VIEW_DOMAIN=${QUOKKABOT_VIEW_DOMAIN:-$(env_value QUOKKABOT_VIEW_DOMAIN)}
  if [[ "$MODE" == dev ]]; then
    QUOKKABOT_DOMAIN=${QUOKKABOT_DOMAIN:-quokkabot.localhost}
    QUOKKABOT_VIEW_DOMAIN=${QUOKKABOT_VIEW_DOMAIN:-view.quokkabot.localhost}
    QUOKKABOT_DEV_PORT=${QUOKKABOT_DEV_PORT:-$(env_value QUOKKABOT_DEV_PORT)}
    QUOKKABOT_DEV_PORT=${QUOKKABOT_DEV_PORT:-8080}
  fi
  [[ -n "$QUOKKABOT_DOMAIN" ]] || die "set QUOKKABOT_DOMAIN (the owner app, for example quokkabot.example.com)"
  [[ -n "$QUOKKABOT_VIEW_DOMAIN" ]] || die "set QUOKKABOT_VIEW_DOMAIN (the live viewer, for example view.quokkabot.example.com)"
  local name
  for name in "$QUOKKABOT_DOMAIN" "$QUOKKABOT_VIEW_DOMAIN"; do
    [[ "$name" =~ ^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9-]{2,63}$ ]] || die "not a lowercase DNS name: $name"
  done
  [[ "$QUOKKABOT_DOMAIN" != "$QUOKKABOT_VIEW_DOMAIN" ]] || die "the app and the viewer need two different names"
  if [[ "$MODE" == prod ]]; then
    APP_ORIGIN="https://$QUOKKABOT_DOMAIN"
    VIEW_ORIGIN="https://$QUOKKABOT_VIEW_DOMAIN"
  else
    [[ "$QUOKKABOT_DOMAIN" == *.localhost && "$QUOKKABOT_VIEW_DOMAIN" == *.localhost ]] ||
      die "--dev serves plain http, which browsers treat as secure only on *.localhost names"
    APP_ORIGIN="http://$QUOKKABOT_DOMAIN:$QUOKKABOT_DEV_PORT"
    VIEW_ORIGIN="http://$QUOKKABOT_VIEW_DOMAIN:$QUOKKABOT_DEV_PORT"
  fi
  QUOKKABOT_RESOLVERS=${QUOKKABOT_RESOLVERS:-$(env_value QUOKKABOT_RESOLVERS)}
  QUOKKABOT_RESOLVERS=${QUOKKABOT_RESOLVERS:-1.1.1.1,9.9.9.9}
  # Optional contact address on the public About and Privacy pages.
  QUOKKABOT_PUBLIC_CONTACT=${QUOKKABOT_PUBLIC_CONTACT:-$(env_value QUOKKABOT_PUBLIC_CONTACT)}
  # Optional iPhone app builds allowed native passkeys on this domain, comma-separated "<team id>.<bundle id>".
  QUOKKABOT_APPLE_APP_IDS=${QUOKKABOT_APPLE_APP_IDS:-$(env_value QUOKKABOT_APPLE_APP_IDS)}
  # Group of the Docker socket as containers see it (the supervisor joins it).
  DOCKER_GID=$(docker run --rm --network none -v /var/run/docker.sock:/var/run/docker.sock:ro \
    caddy:2.11.7@sha256:685ae3d7c34d9b5f8caeddc5d14051db7bbd88ff1f5a2fa0c16bd8ca328fb7af stat -c %g /var/run/docker.sock)
  [[ "$DOCKER_GID" =~ ^[0-9]+$ && "$DOCKER_GID" != 0 ]] || die "the Docker socket's group is '$DOCKER_GID'; it must be a non-root group"
  note "app $APP_ORIGIN, viewer $VIEW_ORIGIN, $QUOKKABOT_AGENTS agent slots, Docker socket group $DOCKER_GID"
}

# Owner and mode changes: set_owner <recursive|single> <uid:gid> <mode> <path>... In --dev the files live on the
# Mac, so ownership is set from inside a container.
set_owner() {
  local depth=$1 owner=$2 mode=$3
  shift 3
  local flag=""
  [[ "$depth" == recursive ]] && flag=-R
  if [[ "$MODE" == prod ]]; then
    chown $flag "$owner" "$@"
    chmod $flag "$mode" "$@"
  else
    docker run --rm --network none -v "$SCRIPT_DIR/.dev:$SCRIPT_DIR/.dev" \
      caddy:2.11.7@sha256:685ae3d7c34d9b5f8caeddc5d14051db7bbd88ff1f5a2fa0c16bd8ca328fb7af \
      sh -c 'flag=$1; owner=$2; mode=$3; shift 3; chown $flag "$owner" "$@" && chmod $flag "$mode" "$@"' \
      sh "$flag" "$owner" "$mode" "$@"
  fi
}

# Creates a directory and sets its own owner and mode; what is inside keeps its owners.
make_dir() {
  local owner=$1 mode=$2 path=$3
  mkdir -p "$path"
  set_owner single "$owner" "$mode" "$path"
}

write_env_file() {
  install -d -m 0700 "$ETC"
  cat >"$ENV_FILE.tmp" <<EOF
# Quokka Bot settings for this server. Written by install.sh; edit and run install.sh again to apply.
QUOKKABOT_DOMAIN=$QUOKKABOT_DOMAIN
QUOKKABOT_VIEW_DOMAIN=$QUOKKABOT_VIEW_DOMAIN
QUOKKABOT_AGENTS=$QUOKKABOT_AGENTS
QUOKKABOT_RESOLVERS=$QUOKKABOT_RESOLVERS
QUOKKABOT_RUNTIME=$RUNTIME
QUOKKABOT_DATA=$DATA
QUOKKABOT_ETC=$ETC
DOCKER_GID=$DOCKER_GID
EOF
  local index entry
  for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
    echo "QUOKKABOT_AGENT_${index}_ID=${AGENT_IDS[index - 1]}" >>"$ENV_FILE.tmp"
  done
  for entry in "${KEPT_AGENT_IDS[@]}"; do
    echo "QUOKKABOT_AGENT_${entry%%=*}_ID=${entry#*=}" >>"$ENV_FILE.tmp"
  done
  if [[ -n "$QUOKKABOT_PUBLIC_CONTACT" ]]; then
    echo "QUOKKABOT_PUBLIC_CONTACT=$QUOKKABOT_PUBLIC_CONTACT" >>"$ENV_FILE.tmp"
  fi
  if [[ -n "$QUOKKABOT_APPLE_APP_IDS" ]]; then
    echo "QUOKKABOT_APPLE_APP_IDS=$QUOKKABOT_APPLE_APP_IDS" >>"$ENV_FILE.tmp"
  fi
  if [[ "$MODE" == dev ]]; then
    echo "QUOKKABOT_DEV_PORT=$QUOKKABOT_DEV_PORT" >>"$ENV_FILE.tmp"
  fi
  chmod 0600 "$ENV_FILE.tmp"
  mv "$ENV_FILE.tmp" "$ENV_FILE"
}

# Canonical secrets: $ETC/secrets/<name>, root only. Each container gets its own copy under
# $ETC/secrets/by-service/<service>/, owned by the user it runs as, mode 0400, mounted read-only at /run/secrets.
readonly SHARED_SECRET_NAMES="db_owner_password db_app_password session_secret audit_hmac_key supervisor_token egress_token"

# agent-<N>/selkies_master_token and agent-<N>/browser_service_token for every slot.
agent_secret_names() {
  local index
  for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
    printf 'agent-%s/selkies_master_token agent-%s/browser_service_token ' "$index" "$index"
  done
}

generate_secrets() {
  log "Secrets"
  install -d -m 0700 "$SECRETS"
  install -d -m 0755 "$SECRETS/by-service"
  local index
  for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
    install -d -m 0700 "$SECRETS/agent-$index"
  done
  local agent_secrets name created=0
  agent_secrets=$(agent_secret_names)
  local all_secrets="$SHARED_SECRET_NAMES $agent_secrets"
  for name in $all_secrets; do
    if [[ ! -s "$SECRETS/$name" ]]; then
      (umask 077 && openssl rand -hex 32 >"$SECRETS/$name")
      created=$((created + 1))
    fi
    chmod 0400 "$SECRETS/$name"
  done
  note "$created new, $(($(wc -w <<<"$all_secrets") - created)) kept"
  # The login vault key: 32 random bytes, base64. Losing it loses every saved login; it never goes into the database.
  if [[ ! -s "$SECRETS/vault_key" ]]; then
    (umask 077 && openssl rand -base64 32 >"$SECRETS/vault_key")
    note "vault key created"
  fi
  chmod 0400 "$SECRETS/vault_key"

  # Updated in place: running containers bind-mount these directories, so the directories must stay the same
  # inodes; files are replaced inside them.
  # google_oauth_client is optional: the owner's Google OAuth client for connecting Gmail, placed by hand.
  local optional=""
  [[ -s "$SECRETS/google_oauth_client" ]] && { chmod 0400 "$SECRETS/google_oauth_client"; optional="google_oauth_client"; }
  # shellcheck disable=SC2086 # the name lists are space-separated words
  sync_service_secrets control "$UID_CONTROL" db_owner_password db_app_password session_secret audit_hmac_key \
    vault_key supervisor_token egress_token $agent_secrets $optional
  # shellcheck disable=SC2086
  sync_service_secrets supervisor "$UID_SANDBOX" supervisor_token $agent_secrets
  sync_service_secrets egress "$UID_EGRESS" egress_token
  sync_service_secrets db "$UID_DB" db_owner_password
}

# sync_service_secrets <service> <uid> <name>...: copies exactly these secrets into by-service/<service>, owned by
# <uid>, files 0400 and directories 0500, and removes anything else there.
sync_service_secrets() {
  local service=$1 uid=$2
  shift 2
  local dir="$SECRETS/by-service/$service" name
  mkdir -p "$dir"
  for name in "$@"; do
    mkdir -p "$(dirname "$dir/$name")"
    install -m 0400 "$SECRETS/$name" "$dir/$name.tmp"
    mv -f "$dir/$name.tmp" "$dir/$name"
  done
  local present wanted
  while IFS= read -r -d '' present; do
    wanted=0
    for name in "$@"; do
      [[ "$present" != "$dir/$name" ]] || wanted=1
    done
    [[ $wanted -eq 1 ]] || rm -f "$present"
  done < <(find "$dir" -type f -print0)
  set_owner recursive "$uid:$uid" u=rX,go= "$dir"
  note "$service: $*"
}

make_data_dirs() {
  log "Data directories under $DATA"
  if [[ "$MODE" == dev && ! -f "$DATA/$MARKER_NAME" ]]; then
    mkdir -p "$DATA"
    echo "dev:unencrypted" >"$DATA/$MARKER_NAME"
  fi
  make_dir "$UID_DB:$UID_DB" 0700 "$DATA/db"
  make_dir 0:0 0700 "$DATA/caddy"
  make_dir 0:0 0700 "$DATA/caddy/data"
  make_dir 0:0 0700 "$DATA/caddy/config"
  make_dir "$UID_SANDBOX:$UID_SANDBOX" 0750 "$DATA/supervisor-socket"
  make_dir "$UID_SANDBOX:$UID_SANDBOX" 0700 "$DATA/runs"
  make_dir 0:0 0755 "$DATA/agents"
  # Signed desktop app builds and their update manifests, served read-only by control at /desktop/.
  make_dir 0:0 0755 "$DATA/desktop"
  local index agent dir
  for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
    agent="$DATA/agents/$index"
    make_dir "$UID_SANDBOX:$UID_SANDBOX" 0700 "$agent"
    for dir in cli-state workspace browser-profile staging run; do
      make_dir "$UID_SANDBOX:$UID_SANDBOX" 0700 "$agent/$dir"
    done
    # Published downloads: the supervisor owns every agent directory as 1000:1000; control (uid 10001, member of
    # group 1000) writes here through the group; the tools sandbox (uid 1000) reads the 0644 files read-only.
    make_dir "$UID_SANDBOX:$UID_SANDBOX" 0775 "$agent/downloads"
  done
  note "agents/1..$QUOKKABOT_AGENTS"
}

# Slots above QUOKKABOT_AGENTS lose their networks and proxy listeners, so their computers must be off. Their stopped
# sandboxes are removed; their data stays and the next computer start recreates them.
check_hidden_slots() {
  local entry index name running
  for entry in "${KEPT_AGENT_IDS[@]}"; do
    index=${entry%%=*}
    for name in cli tools browser; do
      running=$(docker inspect --format '{{.State.Running}}' "qb-$name-$index" 2>/dev/null || true)
      [[ "$running" != true ]] ||
        die "agent slot $index still has a running computer (qb-$name-$index). Stop it in the app or remove the agent, then lower QUOKKABOT_AGENTS"
      if [[ -n "$running" ]]; then
        docker rm "qb-$name-$index" >/dev/null
        note "removed the stopped sandbox qb-$name-$index of hidden slot $index"
      fi
    done
  done
}

# Compose override for the agent slots: each slot's two internal sandbox networks (explicit names so the supervisor
# finds them, explicit bridge names so the host firewall matches them, no address on the host side), the control
# plane and the egress proxy at their fixed addresses on each, and each slot's published downloads in control.
write_agent_compose() {
  local index file="$AGENT_COMPOSE.tmp"
  install -d -m 0700 "$ETC"
  {
    echo "# Written by Quokka Bot install.sh for QUOKKABOT_AGENTS=$QUOKKABOT_AGENTS. Edit quokkabot.env and run install.sh again."
    echo "services:"
    echo "  control:"
    echo "    volumes:"
    echo "      # Published downloads only: never cli-state, workspace, browser-profile or staging."
    for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
      echo "      - \${QUOKKABOT_DATA:-/var/lib/quokkabot}/agents/$index/downloads:/data/agents/$index/downloads"
    done
    echo "    networks:"
    for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
      printf '      qb-cli-%s:\n        ipv4_address: 10.231.%s.3\n' "$index" "$index"
      printf '      qb-browser-%s:\n        ipv4_address: 10.232.%s.3\n' "$index" "$index"
    done
    echo "  egress:"
    echo "    networks:"
    for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
      printf '      qb-cli-%s:\n        ipv4_address: 10.231.%s.2\n' "$index" "$index"
      printf '      qb-browser-%s:\n        ipv4_address: 10.232.%s.2\n' "$index" "$index"
    done
    echo "networks:"
    for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
      local kind bridge subnet
      for kind in cli browser; do
        if [[ $kind == cli ]]; then bridge=qbc$index subnet=10.231.$index.0/24; else bridge=qbb$index subnet=10.232.$index.0/24; fi
        cat <<EOF
  qb-$kind-$index:
    name: qb-$kind-$index
    driver: bridge
    internal: true
    enable_ipv6: false
    driver_opts:
      com.docker.network.bridge.name: $bridge
      com.docker.network.bridge.inhibit_ipv4: "true"
    ipam:
      config:
        - subnet: $subnet
EOF
      done
    done
  } >"$file"
  chmod 0644 "$file"
  mv "$file" "$AGENT_COMPOSE"
}

# Gateways of the fixed networks and of every agent slot's networks, refused by the egress proxy even before Docker
# has created them.
known_gateways() {
  local index
  printf '%s\n' $BASE_GATEWAYS
  for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
    printf '10.231.%s.1\n10.232.%s.1\n' "$index" "$index"
  done
}

