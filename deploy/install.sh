#!/usr/bin/env bash
# Quokka Bot installer. Idempotent: run it again to apply changes, rebuild images and restart what changed.
#
#   QUOKKABOT_DOMAIN=quokkabot.example.com QUOKKABOT_VIEW_DOMAIN=view.quokkabot.example.com \
#     /opt/quokkabot/src/deploy/install.sh [--setup-volume /dev/sdX]
#
#   deploy/install.sh --dev      local development on OrbStack or Docker Desktop (see docs/install.md)
#
# Production (Ubuntu 24.04, root): installs Docker and gVisor when missing, requires the encrypted data volume at
# /var/lib/quokkabot, turns core dumps off, installs the host firewall, generates secrets and configs under
# /etc/quokkabot, builds the images from this repository, starts the stack and prints the owner setup link.
set -Eeuo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SRC=$(cd "$SCRIPT_DIR/.." && pwd)
readonly SCRIPT_DIR SRC
readonly MAPPER_NAME=quokkabot-data
readonly MARKER_NAME=.quokkabot-volume
readonly VOLUME_KEY=/etc/quokkabot/volume.key

# Fixed layout (the addresses are spelled out in compose.yaml and in write_configs below): edge 10.230.0.0/24
# (caddy .2, control .3), db 10.230.1.0/24, ctl 10.230.2.0/24 (egress .2, control .3), out 10.230.3.0/24.
# Agent slot N: qb-cli-N 10.231.N.0/24 and qb-browser-N 10.232.N.0/24 on bridges qbcN and qbbN (egress .2,
# control .3, sandbox .10). QUOKKABOT_AGENTS (default 4) sets how many slots exist; the owner creates agents in them
# from the app. Each slot's networks, addresses, secrets and directories are provisioned here, never at runtime.
readonly DEFAULT_AGENTS=4
readonly MAX_AGENTS=99
readonly BASE_GATEWAYS="10.230.0.1 10.230.1.1 10.230.2.1 10.230.3.1"

# Container users (see the root Dockerfile and deploy/compose.yaml).
readonly UID_SANDBOX=1000 UID_CONTROL=10001 UID_EGRESS=10002 UID_DB=999

log() { printf '\033[1m==> %s\033[0m\n' "$*"; }
note() { printf '    %s\n' "$*"; }
die() {
  printf 'install.sh: %s\n' "$*" >&2
  exit 1
}
trap 'die "failed at line $LINENO: $BASH_COMMAND"' ERR

usage() {
  sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

MODE=prod
SETUP_VOLUME_DEVICE=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --setup-volume)
      [[ $# -ge 2 ]] || die "--setup-volume needs a block device, for example /dev/sdb"
      SETUP_VOLUME_DEVICE=$2
      shift 2
      ;;
    --dev)
      MODE=dev
      shift
      ;;
    -h | --help) usage 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
done

if [[ "$MODE" == prod ]]; then
  ETC=/etc/quokkabot
  DATA=/var/lib/quokkabot
  RUNTIME=runsc
  COMPOSE_FILES=(-f "$SCRIPT_DIR/compose.yaml")
  COMPOSE_WRAPPER=/usr/local/bin/quokkabot-compose
else
  [[ -z "$SETUP_VOLUME_DEVICE" ]] || die "--setup-volume is for production servers only"
  ETC="$SCRIPT_DIR/.dev/etc"
  DATA="$SCRIPT_DIR/.dev/data"
  RUNTIME=runc
  COMPOSE_FILES=(-f "$SCRIPT_DIR/compose.yaml" -f "$SCRIPT_DIR/compose.dev.yaml")
  COMPOSE_WRAPPER="$SCRIPT_DIR/.dev/quokkabot-compose"
fi
readonly ETC DATA RUNTIME COMPOSE_WRAPPER MODE
readonly ENV_FILE="$ETC/quokkabot.env"
readonly SECRETS="$ETC/secrets"
# Generated by write_agent_compose: every agent slot's networks and the control plane's and proxy's places on them.
readonly AGENT_COMPOSE="$ETC/compose.agents.yaml"
COMPOSE_FILES+=(-f "$AGENT_COMPOSE")

compose() {
  docker compose --project-directory "$SCRIPT_DIR" --env-file "$ENV_FILE" "${COMPOSE_FILES[@]}" "$@"
}

