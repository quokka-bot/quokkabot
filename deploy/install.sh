check_host() {
  log "Checking the host"
  [[ $EUID -eq 0 ]] || die "run as root"
  [[ -r /etc/os-release ]] || die "/etc/os-release is missing"
  local id version
  id=$(. /etc/os-release && echo "${ID:-}")
  version=$(. /etc/os-release && echo "${VERSION_ID:-}")
  [[ "$id" == ubuntu && "$version" == 24.04 ]] || die "Ubuntu 24.04 is required (found $id $version)"
  case "$(dpkg --print-architecture)" in
    amd64 | arm64) ;;
    *) die "amd64 or arm64 is required" ;;
  esac
  if [[ -n "$(swapon --noheadings --show 2>/dev/null)" ]]; then
    die "swap is active; Quokka Bot keeps credentials in memory that must not reach an unencrypted disk. Turn it off (swapoff -a and remove it from /etc/fstab), then run again"
  fi
  note "Ubuntu $version $(dpkg --print-architecture), no swap"
}

install_packages() {
  local missing=()
  local package
  for package in ca-certificates curl gnupg cryptsetup nftables python3 openssl util-linux restic rsync; do
    dpkg-query -W -f='${Status}' "$package" 2>/dev/null | grep -q "install ok installed" || missing+=("$package")
  done
  if [[ ${#missing[@]} -gt 0 ]]; then
    log "Installing ${missing[*]}"
    DEBIAN_FRONTEND=noninteractive apt-get update -q
    DEBIAN_FRONTEND=noninteractive apt-get install -y -q "${missing[@]}"
  fi
}

install_docker() {
  if command -v docker >/dev/null && docker compose version >/dev/null 2>&1 && docker buildx version >/dev/null 2>&1; then
    note "Docker $(docker version --format '{{.Server.Version}}'), Compose $(docker compose version --short)"
    return
  fi
  log "Installing Docker from download.docker.com"
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  printf 'deb [arch=%s signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu %s stable\n' \
    "$(dpkg --print-architecture)" "$(. /etc/os-release && echo "$VERSION_CODENAME")" >/etc/apt/sources.list.d/docker.list
  DEBIAN_FRONTEND=noninteractive apt-get update -q
  DEBIAN_FRONTEND=noninteractive apt-get install -y -q docker-ce docker-ce-cli containerd.io docker-buildx-plugin \
    docker-compose-plugin
  systemctl enable --now docker
}

install_gvisor() {
  if ! command -v runsc >/dev/null; then
    log "Installing gVisor (runsc) from gvisor.dev"
    curl -fsSL https://gvisor.dev/archive.key | gpg --dearmor --yes -o /usr/share/keyrings/gvisor-archive-keyring.gpg
    printf 'deb [arch=%s signed-by=/usr/share/keyrings/gvisor-archive-keyring.gpg] https://storage.googleapis.com/gvisor/releases release main\n' \
      "$(dpkg --print-architecture)" >/etc/apt/sources.list.d/gvisor.list
    DEBIAN_FRONTEND=noninteractive apt-get update -q
    DEBIAN_FRONTEND=noninteractive apt-get install -y -q runsc
  fi
  note "$(runsc --version | head -1)"
}

# Registers runsc with Docker and sets a zero core-dump limit for every container. Restarts Docker only when
# daemon.json changed.
configure_docker_daemon() {
  local file=/etc/docker/daemon.json before after
  mkdir -p /etc/docker
  [[ -f "$file" ]] || echo '{}' >"$file"
  before=$(sha256sum "$file")
  if ! python3 -c 'import json,sys; sys.exit(0 if "runsc" in json.load(open(sys.argv[1])).get("runtimes", {}) else 1)' "$file"; then
    runsc install
  fi
  python3 - "$file" <<'PY'
import json, sys
path = sys.argv[1]
with open(path) as f:
    config = json.load(f)
config.setdefault("default-ulimits", {})["core"] = {"Name": "core", "Hard": 0, "Soft": 0}
with open(path + ".tmp", "w") as f:
    json.dump(config, f, indent=2)
    f.write("\n")
PY
  mv "$file.tmp" "$file"
  after=$(sha256sum "$file")
  if [[ "$before" != "$after" ]]; then
    log "Restarting Docker for the daemon.json change"
    systemctl restart docker
  fi
  docker info --format '{{range $name, $_ := .Runtimes}}{{$name}} {{end}}' | grep -qw runsc || die "Docker does not list the runsc runtime"
  [[ "$(docker info --format '{{.DriverStatus}}')" == *io.containerd.snapshotter* ]] ||
    die "Docker must use the containerd image store (locally built images need digests); see docs/install.md"
}

setup_volume() {
  local device=$1
  log "Setting up the encrypted data volume on $device"
  [[ -b "$device" ]] || die "$device is not a block device"
  mountpoint -q "$DATA" && die "$DATA is already a mount point"
  local root_disk
  root_disk=$(lsblk -n -o PKNAME "$(findmnt -n -o SOURCE /)" | head -1)
  [[ "$(lsblk -n -d -o NAME "$device")" != "$root_disk" ]] || die "$device holds the root filesystem"
  [[ $(lsblk -n -o NAME "$device" | wc -l) -eq 1 ]] || die "$device has partitions; use an empty device"
  if blkid -p "$device" >/dev/null 2>&1; then
    die "$device already carries a filesystem or LUKS header ($(blkid -p -o value -s TYPE "$device")). Wipe it yourself (wipefs -a $device) if you mean to replace it"
  fi
  install -d -m 0700 /etc/quokkabot
  if [[ ! -f "$VOLUME_KEY" ]]; then
    head -c 64 /dev/urandom >"$VOLUME_KEY"
    chmod 0400 "$VOLUME_KEY"
  fi
  cryptsetup luksFormat --type luks2 --batch-mode --key-file "$VOLUME_KEY" "$device"
  local uuid
  uuid=$(cryptsetup luksUUID "$device")
  cryptsetup open --key-file "$VOLUME_KEY" "$device" "$MAPPER_NAME"
  mkfs.ext4 -q -L quokkabot-data "/dev/mapper/$MAPPER_NAME"
  sed -i "/^${MAPPER_NAME}[[:space:]]/d" /etc/crypttab 2>/dev/null || true
  printf '%s UUID=%s %s luks,discard\n' "$MAPPER_NAME" "$uuid" "$VOLUME_KEY" >>/etc/crypttab
  sed -i "\#^/dev/mapper/${MAPPER_NAME}[[:space:]]#d" /etc/fstab
  printf '/dev/mapper/%s %s ext4 defaults,nodev,nosuid 0 2\n' "$MAPPER_NAME" "$DATA" >>/etc/fstab
  systemctl daemon-reload
  install -d -m 0755 "$DATA"
  mount "$DATA"
  printf 'luks:%s\n' "$uuid" >"$DATA/$MARKER_NAME"
  chmod 0644 "$DATA/$MARKER_NAME"
  note "LUKS2 $uuid, key $VOLUME_KEY, mounted at $DATA"
}

check_volume() {
  log "Checking the encrypted data volume"
  mountpoint -q "$DATA" ||
    die "$DATA is not a mount point. Attach a dedicated volume and run with --setup-volume <device>"
  local source mapper backing uuid marker
  source=$(findmnt -n -o SOURCE --target "$DATA")
  [[ "$(lsblk -n -d -o TYPE "$source")" == crypt ]] || die "$DATA is mounted from $source, which is not a dm-crypt device"
  [[ -f "$DATA/$MARKER_NAME" ]] || die "$DATA/$MARKER_NAME is missing; this is not the Quokka Bot volume"
  mapper=${source##*/}
  backing=$(cryptsetup status "$mapper" | awk '$1 == "device:" {print $2}')
  uuid=$(cryptsetup luksUUID "$backing")
  marker=$(<"$DATA/$MARKER_NAME")
  [[ "$marker" == "luks:$uuid" ]] || die "$DATA/$MARKER_NAME says '$marker' but the mounted volume is luks:$uuid"
  note "$source (LUKS $uuid on $backing)"
}

# Docker starts only after the data volume is mounted and the Quokka Bot firewall is loaded.
order_docker_after_volume() {
  local dropin=/etc/systemd/system/docker.service.d/10-quokkabot.conf
  install -d -m 0755 "$(dirname "$dropin")"
  cat >"$dropin.tmp" <<EOF
# Written by Quokka Bot install.sh.
[Unit]
RequiresMountsFor=$DATA
Requires=quokkabot-firewall.service
After=quokkabot-firewall.service
EOF
  if ! cmp -s "$dropin.tmp" "$dropin"; then
    mv "$dropin.tmp" "$dropin"
    systemctl daemon-reload
  else
    rm -f "$dropin.tmp"
  fi
}

disable_core_dumps() {
  log "Turning core dumps off"
  cat >/etc/sysctl.d/90-quokkabot.conf <<'EOF'
# Written by Quokka Bot install.sh: no core dumps (they would copy credentials out of memory).
kernel.core_pattern=|/bin/false
fs.suid_dumpable=0
EOF
  sysctl -q -p /etc/sysctl.d/90-quokkabot.conf
  printf '# Written by Quokka Bot install.sh.\n* hard core 0\n* soft core 0\n' >/etc/security/limits.d/90-quokkabot.conf
  install -d -m 0755 /etc/systemd/coredump.conf.d
  printf '# Written by Quokka Bot install.sh.\n[Coredump]\nStorage=none\nProcessSizeMax=0\n' \
    >/etc/systemd/coredump.conf.d/90-quokkabot.conf
  note "kernel.core_pattern=$(sysctl -n kernel.core_pattern), fs.suid_dumpable=$(sysctl -n fs.suid_dumpable)"
}

install_firewall() {
  log "Installing the host firewall"
  local backend
  backend=$(docker info --format '{{.FirewallBackend.Driver}}' 2>/dev/null || true)
  case "$backend" in
    iptables | nftables) note "Docker firewall backend: $backend ($(iptables --version 2>/dev/null || echo 'iptables not installed'))" ;;
    *) die "unknown Docker firewall backend '$backend'; expected iptables or nftables" ;;
  esac
  # Rules for every agent slot 1..N live in one table.
  local ifaces="" same_bridge="" index
  for ((index = 1; index <= QUOKKABOT_AGENTS; index++)); do
    ifaces+="${ifaces:+, }\"qbc$index\", \"qbb$index\""
    same_bridge+="${same_bridge:+$'\n'}$(printf '\t\tiifname "qbc%s" oifname "qbc%s" accept\n\t\tiifname "qbb%s" oifname "qbb%s" accept' \
      "$index" "$index" "$index" "$index")"
  done
  local subnets="10.231.0.0/16, 10.232.0.0/16"
  local rendered
  rendered=$(sed -e "s|@SANDBOX_IFACES@|$ifaces|" -e "s|@SANDBOX_SUBNETS@|$subnets|" "$SCRIPT_DIR/nftables.conf.in")
  rendered=${rendered/@SAME_BRIDGE_ACCEPT@/$same_bridge}
  install -d -m 0700 "$ETC"
  printf '%s\n' "$rendered" >"$ETC/nftables.conf.tmp"
  chmod 0600 "$ETC/nftables.conf.tmp"
  nft -c -f "$ETC/nftables.conf.tmp" || die "the rendered nftables rules do not parse"
  mv "$ETC/nftables.conf.tmp" "$ETC/nftables.conf"
  install -m 0644 "$SCRIPT_DIR/quokkabot-firewall.service" /etc/systemd/system/quokkabot-firewall.service
  systemctl daemon-reload
  systemctl enable --quiet quokkabot-firewall.service
  # docker.service Requires= this unit, so a restart would restart Docker and every container; reload instead.
  if systemctl is-active --quiet quokkabot-firewall.service; then
    systemctl reload quokkabot-firewall.service
  else
    systemctl start quokkabot-firewall.service
  fi
  nft list table inet quokkabot >/dev/null || die "table inet quokkabot is not loaded"
  note "table inet quokkabot loaded; drops host input from qbc1..qbc$QUOKKABOT_AGENTS, qbb1..qbb$QUOKKABOT_AGENTS and 10.231/16, 10.232/16"
}

